// On phones the sections below the first screens skip layout until they come near the screen
// (content-visibility), holding the height they really have so the page never drifts after a jump.
// This measures those heights on the production build and writes src/app/held.css. Area and contact
// change with each lead (map, name, address), so they always lay out normally.
// Run after a build whenever section content changes, then build again:   node scripts/held-heights.mjs
import { writeFile } from "node:fs/promises";
import path from "node:path";
import { ORIGIN, openBrowser, openPage } from "./offline.mjs";

const SECTIONS = ["#usluge", "#kvar", "#cene", '[aria-labelledby="process-title"]', "#radovi", '[aria-labelledby="report-title"]', "#utisci", "#pitanja"];
const WIDTHS = [...Array.from({ length: 33 }, (_, i) => 320 + i * 5), ...Array.from({ length: 14 }, (_, i) => 500 + i * 20), 767];
const MAX = 767;

const browser = await openBrowser();
const table = [];
for (const width of WIDTHS) {
  const page = await openPage(browser, { width, height: 800, mobile: true, scale: 2 });
  await page.addInitScript(() => {
    document.addEventListener("DOMContentLoaded", () => {
      const st = document.createElement("style");
      st.textContent = "#main > section { content-visibility: visible !important }";
      document.head.append(st);
    });
  });
  await page.goto(`${ORIGIN}/`, { waitUntil: "load" });
  await page.evaluate(() => document.fonts.ready);
  await page.waitForTimeout(400);
  // contain-intrinsic-size holds the content box, so padding and borders come off
  const hs = await page.evaluate(
    (sel) =>
      sel.map((s) => {
        const el = document.querySelector(s);
        const c = getComputedStyle(el);
        const edges = ["paddingTop", "paddingBottom", "borderTopWidth", "borderBottomWidth"].reduce((sum, k) => sum + parseFloat(c[k]), 0);
        return Math.round((el.getBoundingClientRect().height - edges) * 10) / 10;
      }),
    SECTIONS,
  );
  if (page.errors.length) console.log(width, page.errors.slice(0, 3));
  table.push([width, hs]);
  await page.context().close();
}
await browser.close();

// Ascending min-width steps; each step only restates the sections whose height changed
let css = `/* Generated by scripts/held-heights.mjs from the production build. Do not edit by hand. */\n\n@media (max-width: ${MAX}px) {\n  ${SECTIONS.join(",\n  ")} {\n    content-visibility: auto;\n    contain-intrinsic-size: auto var(--held);\n  }\n}\n`;
let prev = [];
for (const [width, hs] of table) {
  const rules = SECTIONS.map((s, i) => (prev[i] === hs[i] ? "" : `  ${s} { --held: ${hs[i]}px; }\n`)).join("");
  if (!rules) continue;
  css += width === WIDTHS[0] ? `@media (max-width: ${MAX}px) {\n${rules}}\n` : `@media (min-width: ${width}px) and (max-width: ${MAX}px) {\n${rules}}\n`;
  prev = hs;
}
await writeFile(path.resolve(import.meta.dirname, "../src/app/held.css"), css);
console.log(`held.css: ${table.length} widths`);
for (const w of [320, 375, 430]) console.log(w, table.find(([x]) => x === w)[1].join(" "));
