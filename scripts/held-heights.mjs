// On phones the sections below the first screens skip layout until they come near the screen
// (content-visibility), holding the height they really have so the page never drifts after a jump.
// This measures those heights on the production build and writes src/app/held.css. Serbian and English
// are measured separately (<main data-lang>); previews use the heights of their language. Area, contact
// and the footer change with each lead (map, name, address), so they only hold a height on the concept
// pages (<main> without data-preview); on previews they always lay out normally.
// Run after a build whenever section content changes, then build again:   node scripts/held-heights.mjs
import { writeFile } from "node:fs/promises";
import path from "node:path";
import { ORIGIN, openBrowser, openPage } from "./offline.mjs";

const SECTIONS = ["#usluge", "#utisci", "#kvar", '[aria-labelledby="report-title"]', "#cene", "#radovi", '[aria-labelledby="plan-title"]', '[aria-labelledby="process-title"]', "#pitanja"];
// On the concept pages only; `~ footer` because the footer follows <main>
const CONCEPT = ["#teren", "#kontakt", "footer"];
const ALL = [...SECTIONS, ...CONCEPT];
const sel = (prefix, s) => (s === "footer" ? `${prefix} ~ footer` : `${prefix} > ${s}`);
const LANGS = [
  ["sr", "/"],
  ["en", "/en"],
];
const WIDTHS = [...Array.from({ length: 33 }, (_, i) => 320 + i * 5), ...Array.from({ length: 14 }, (_, i) => 500 + i * 20), 767];
const MAX = 767;

const browser = await openBrowser();
const tables = {};
for (const [lang, route] of LANGS) {
  const table = (tables[lang] = []);
  for (const width of WIDTHS) {
    const page = await openPage(browser, { width, height: 800, mobile: true, scale: 2 });
    await page.addInitScript(() => {
      document.addEventListener("DOMContentLoaded", () => {
        const st = document.createElement("style");
        st.textContent = "#main > section, footer { content-visibility: visible !important }";
        document.head.append(st);
      });
    });
    await page.goto(ORIGIN + route, { waitUntil: "load" });
    await page.evaluate(() => document.fonts.ready);
    // The open badge settles when the page is idle
    await page.waitForTimeout(800);
    // contain-intrinsic-size holds the content box, so padding and borders come off
    const hs = await page.evaluate(
      (list) =>
        list.map((s) => {
          const el = document.querySelector(s === "footer" ? "#main ~ footer" : s);
          const c = getComputedStyle(el);
          const edges = ["paddingTop", "paddingBottom", "borderTopWidth", "borderBottomWidth"].reduce((sum, k) => sum + parseFloat(c[k]), 0);
          return Math.round((el.getBoundingClientRect().height - edges) * 10) / 10;
        }),
      ALL,
    );
    if (page.errors.length) console.log(lang, width, page.errors.slice(0, 3));
    table.push([width, hs]);
    await page.context().close();
  }
}
await browser.close();

// Ascending min-width steps; each step only restates the sections whose height changed
const held = [...SECTIONS, ...CONCEPT.map((s) => sel("#main:not([data-preview])", s))];
let css = `/* Generated by scripts/held-heights.mjs from the production build. Do not edit by hand. */\n\n@media (max-width: ${MAX}px) {\n  ${held.join(",\n  ")} {\n    content-visibility: auto;\n    contain-intrinsic-size: auto var(--held);\n  }\n}\n`;
for (const [lang] of LANGS) {
  let prev = [];
  for (const [width, hs] of tables[lang]) {
    const rules = ALL.map((s, i) => (prev[i] === hs[i] ? "" : `  ${sel(`[data-lang="${lang}"]`, s)} { --held: ${hs[i]}px; }\n`)).join("");
    if (!rules) continue;
    css += width === WIDTHS[0] ? `@media (max-width: ${MAX}px) {\n${rules}}\n` : `@media (min-width: ${width}px) and (max-width: ${MAX}px) {\n${rules}}\n`;
    prev = hs;
  }
}
await writeFile(path.resolve(import.meta.dirname, "../src/app/held.css"), css);
for (const [lang] of LANGS) {
  console.log(`${lang}: ${tables[lang].length} widths   (${ALL.join(" ")})`);
  for (const w of [320, 375, 430]) console.log(" ", w, tables[lang].find(([x]) => x === w)[1].join(" "));
}
